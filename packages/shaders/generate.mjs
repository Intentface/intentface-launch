// Regenerates definitions.ts and the optimizeDeps list in package.json from
// the installed `shaders` package. Run after upgrading it: node generate.mjs
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const here = dirname(new URL(import.meta.url).pathname);
// The package exports no ./package.json, so read it from node_modules.
const lib = join(here, "node_modules/shaders");
const exports = JSON.parse(readFileSync(join(lib, "package.json"), "utf8")).exports;

// Components with a module of their own (the package lists a few that it does not ship).
const names = Object.entries(exports)
  .filter(([key, value]) => /^\.\/core\/[A-Z]/.test(key) && existsSync(join(lib, value.import)))
  .map(([key]) => key.slice("./core/".length))
  .sort();

writeFileSync(
  join(here, "definitions.ts"),
  `// Generated by generate.mjs from shaders@${JSON.parse(readFileSync(join(lib, "package.json"), "utf8")).version}: do not edit.
// Each component's definition, loaded when a video first uses it. They come
// from the same module graph as \`shaders/core\`, whose renderer compares
// some of their functions by identity.

import type { GpuShaderDefinition } from "shaders/core";

type Loader = () => Promise<{ componentDefinition: unknown }>;

export const definitions: Record<string, Loader> = {
${names.map((n) => `  ${n}: () => import("shaders/core/${n}"),`).join("\n")}
};

export type ComponentType = ${names.map((n) => `"${n}"`).join(" | ")};

export const load = async (type: string) =>
  (await definitions[type]?.())?.componentDefinition as GpuShaderDefinition | undefined;
`,
);

const pkgFile = join(here, "package.json");
const pkg = JSON.parse(readFileSync(pkgFile, "utf8"));
// Paper's shaders (paper.tsx) are one module, kept at the head of the list.
pkg["intentface-launch"].optimizeDeps = [
  "@paper-design/shaders",
  "shaders/core",
  ...names.map((n) => `shaders/core/${n}`),
];
writeFileSync(pkgFile, `${JSON.stringify(pkg, null, 2)}\n`);
execFileSync("pnpm", ["exec", "biome", "format", "--write", "definitions.ts", "package.json"], { cwd: here });
console.log(`${names.length} components`);
